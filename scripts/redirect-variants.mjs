// Runs before `next build`. Writes permanent (301) redirects for the
// trailing-slash and .html variants of every page in public/sitemap.xml into a
// generated block of public/_redirects. Without them, Cloudflare's asset
// handling (html_handling: drop-trailing-slash) answers those variants with a
// temporary 307. Rules are written per URL rather than as a splat, so "/" can
// never match a rule and loop.
import fs from 'node:fs';

const SITEMAP = 'public/sitemap.xml';
const REDIRECTS = 'public/_redirects';
const BASE = 'https://getmylocations.com';
const START = '# BEGIN generated by scripts/redirect-variants.mjs (do not edit by hand)';
const END = '# END generated';

const paths = [...fs.readFileSync(SITEMAP, 'utf8').matchAll(/<loc>([^<]+)<\/loc>/g)]
  .map((m) => m[1].trim().replace(BASE, ''))
  .filter((p) => p && p !== '/');
if (!paths.length) throw new Error('redirect-variants: no URLs found in the sitemap');

const rules = paths.flatMap((p) => [`${p}/  ${p}  301`, `${p}.html  ${p}  301`]);
const block = [START, '# Trailing-slash and .html variants of each sitemap URL -> the canonical URL.', ...rules, END].join('\n');

const current = fs.readFileSync(REDIRECTS, 'utf8');
const re = new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END}`);
const next = re.test(current) ? current.replace(re, block) : `${current.trimEnd()}\n\n${block}\n`;
if (next !== current) {
  fs.writeFileSync(REDIRECTS, next);
  console.log(`redirect-variants: ${rules.length} rules for ${paths.length} URLs`);
}
